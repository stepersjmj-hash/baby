/* ============================================================
   trace/dots.js — 점 잇기
   ------------------------------------------------------------
   1 → 2 → 3 순서대로 이으면 그림이 나온다. 역시 같은 판정 엔진이고,
   길을 그려 주지 않는 대신 번호 붙은 점을 찍는다
   (runner 의 guide:false + level.dots).

   점 사이가 멀어서 허용 오차를 넉넉히 준다 — 아이 손으로 그은 선은
   가운데가 활처럼 휘기 때문이다.
   ============================================================ */

import { poly } from '../core/trace.js';

/** 점 목록을 순서대로 잇는다. closed 면 마지막에서 1번으로 돌아온다 */
const pic = (id, name, ico, dots, closed = true) => ({
  id, name, ico, from: '✏️', to: ico, dots,
  strokes: [poly(closed ? [...dots, dots[0]] : dots)],
  tol: 66
});

/** 꼭짓점 n 개짜리 별 */
function star(cx, cy, R, r, n = 5) {
  const out = [];
  for (let i = 0; i < n * 2; i++) {
    const a = -Math.PI / 2 + (i * Math.PI) / n;
    const rad = i % 2 ? r : R;
    out.push([cx + Math.cos(a) * rad, cy + Math.sin(a) * rad]);
  }
  return out;
}

