/* ============================================================
   trace/dots.js — 점 잇기
   ------------------------------------------------------------
   1 → 2 → 3 순서대로 이으면 그림이 나온다. 역시 같은 판정 엔진이고,
   길을 그려 주지 않는 대신 번호 붙은 점을 찍는다
   (runner 의 guide:false + level.dots).

   점 사이가 멀어서 허용 오차를 넉넉히 준다 — 아이 손으로 그은 선은
   가운데가 활처럼 휘기 때문이다.

   **단계 id 가 곧 그림 이름**이다 (house · crown · fish · car · star) —
   칩과 도착점 그림을 `core/icons.js` 의 picIcon 이 그걸로 찾는다.
   ============================================================ */

import { poly } from '../core/trace.js';

/** 점 목록을 순서대로 잇는다. closed 면 마지막에서 1번으로 돌아온다.
    hard 는 칩의 난이도 띠 (점이 많을수록 어렵다: ~7 쉬움 · 8~10 보통 · 11~ 어려움).

    tol 은 **가장 가까운 이웃 점 사이의 절반**으로 잡는다 — 그보다 넉넉하면
    옆 점으로 건너뛰어 안 이은 구간이 통과된다. 대신 40 아래로는 안 내린다:
    아이 손으로 그은 선은 가운데가 활처럼 휘어서, 너무 조이면 진행이 멈춘다. */
const pic = (id, name, hard, dots, closed = true) => {
  const ring = closed ? [...dots, dots[0]] : dots;
  let gap = Infinity;
  for (let i = 1; i < ring.length; i++)
    gap = Math.min(gap, Math.hypot(ring[i][0] - ring[i - 1][0], ring[i][1] - ring[i - 1][1]));
  return {
    id, name, hard, dots,
    strokes: [poly(ring)],
    tol: Math.max(40, Math.min(66, Math.round(gap / 2)))
  };
};

/** 꼭짓점 n 개짜리 별 */
function star(cx, cy, R, r, n = 5) {
  const out = [];
  for (let i = 0; i < n * 2; i++) {
    const a = -Math.PI / 2 + (i * Math.PI) / n;
    const rad = i % 2 ? r : R;
    out.push([cx + Math.cos(a) * rad, cy + Math.sin(a) * rad]);
  }
  return out;
}

