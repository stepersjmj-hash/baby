/* ============================================================
   trace/numbers.js — 숫자 쓰기: 1~19 · 십 단위 20~100
   ------------------------------------------------------------
   좌표계 1000×700. 곡선은 arc() 를 poly() 에 펼쳐 넣어 만든다.
   한 획짜리 숫자는 굴곡이 심하므로 tol 을 조금 줄였다 —
   경로가 자기 자신에게 가까워지는 곳(8 의 가운데)에서 건너뛰지 않게.
   ============================================================ */

import { poly, arc } from '../core/trace.js';
const PI = Math.PI;

export const NUMBERS = [
  { id: 'n1', name: '1', strokes: [poly([[400, 245], [500, 155], [500, 560]])] },

  { id: 'n2', name: '2', strokes: [poly([...arc(500, 265, 115, 115, PI, 2 * PI, 24),
                                         [385, 555], [625, 555]])] },

  { id: 'n3', name: '3', strokes: [poly([...arc(500, 255, 110, 105, PI * 1.05, PI * 2.45, 24),
                                         ...arc(500, 455, 110, 105, PI * 1.55, PI * 2.75, 24)])] },

  { id: 'n4', name: '4', strokes: [poly([[600, 155], [320, 405], [700, 405]]),
                                   poly([[600, 215], [600, 560]])] },

  // 배 부분은 왼쪽 위에서 시작해 위 → 오른쪽 → 아래 → 왼쪽 아래로 한 바퀴 가까이 돈다.
  // 각이 커지는 쪽이 화면상 시계 방향이므로 끝 각을 시작보다 크게 둬야 한다.
  { id: 'n5', name: '5', strokes: [poly([[380, 175], [380, 370],
                                         ...arc(495, 455, 112, 105, PI * 1.15, PI * 2.8, 26)]),
                                   poly([[380, 175], [645, 175]])] },

  // 6 은 오른쪽 위에서 왼쪽으로 부풀며 내려온 뒤 아래에서 한 바퀴 돈다.
  // 둘 다 각이 작아지는 쪽(화면상 반시계)이다 — 커지는 쪽으로 두면 ə 모양이 된다.
  { id: 'n6', name: '6', strokes: [poly([...arc(520, 350, 130, 200, -PI * 0.4, -PI * 1.5, 26),
                                         ...arc(505, 450, 105, 105, PI * 0.5, -PI * 1.5, 30)])],
    tol: 36 },

  { id: 'n7', name: '7', strokes: [poly([[350, 190], [660, 190], [430, 560]])] },

  { id: 'n8', name: '8', strokes: [poly([...arc(500, 255, 100, 100, PI * 0.5, PI * 2.5, 30),
                                         ...arc(500, 455, 100, 100, -PI * 0.5, PI * 1.5, 30)])],
    tol: 34 },

  { id: 'n9', name: '9', strokes: [poly([...arc(500, 285, 110, 110, 0, -2 * PI, 30),
                                         [610, 555]])],
    tol: 36 },

  { id: 'n10', name: '10', strokes: [poly([[240, 250], [330, 160], [330, 560]]),
                                     poly(arc(620, 360, 115, 200, -PI / 2, -PI * 2.5, 36))] }   // 0 은 반시계
].map(L => ({ ...L, ico: L.name }));

/* ── 11~19 · 십 단위 20~100 ─────────────────────────────
   위 낱자 획을 좁혀(remap) 나란히 놓는다. 획순은 왼쪽 숫자부터.
   6·8·9 는 좁아진 만큼 궤도가 붙어서 tol 을 더 조인다. */
const remap = (fn, cx, k) => t => {
  const q = fn(t);
  return { x: cx + (q.x - 500) * k, y: q.y };
};
const ZERO = poly(arc(500, 355, 165, 210, -PI / 2, -PI * 2.5, 36));   // 0 은 반시계
const DIGIT = Object.fromEntries(NUMBERS.map(L => [L.name, L.strokes]));

/* 11~19: 왼쪽 1 은 n10 의 것을 그대로 써서 10 과 나란히 보이게 하고,
   오른쪽 낱자만 십 단위와 같은 비율로 좁힌다. */
const ONE = poly([[240, 250], [330, 160], [330, 560]]);
for (let d = 1; d <= 9; d++) {
  NUMBERS.push({
    id: 'n1' + d, name: '1' + d, ico: '1' + d,
    tol: (d === 6 || d === 8 || d === 9) ? 28 : 36,
    strokes: [ONE, ...DIGIT[String(d)].map(f => remap(f, 625, 0.52))]
  });
}

for (let d = 2; d <= 9; d++) {
  NUMBERS.push({
    id: 'n' + d + '0', name: d + '0', ico: d + '0',
    tol: (d === 6 || d === 8 || d === 9) ? 28 : 36,
    strokes: [...DIGIT[String(d)].map(f => remap(f, 375, 0.52)),
              remap(ZERO, 625, 0.52)]
  });
}
NUMBERS.push({
  id: 'n100', name: '100', ico: '100', tol: 30,
  strokes: [...DIGIT['1'].map(f => remap(f, 300, 0.38)),
            remap(ZERO, 520, 0.38), remap(ZERO, 715, 0.38)]
});
