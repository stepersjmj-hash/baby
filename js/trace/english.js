/* 대문자와 모양이 같은 소문자(c·o·s·u·v·w·x·z)는 밑줄을 기준으로
   몸통 높이만큼 줄여서 쓴다 — 따로 그릴 이유가 없다 */
const XK = (BASE - XT) / (BASE - TOP);
const small = (fn) => (t) => {
  const q = fn(t);
  return { x: 500 + (q.x - 500) * XK, y: BASE - (BASE - q.y) * XK };
};
const smallOf = (ch) => UPPER_STROKES[ch].map(small);

