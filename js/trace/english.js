/* ============================================================
   trace/english.js — 알파벳 A~Z: 대문자 + 소문자 한 쌍
   ------------------------------------------------------------
   한 단계에 **대문자를 쓰고 이어서 소문자를 쓴다** (왼쪽 A, 오른쪽 a).
   아이는 두 모양을 따로 배워야 하는데 같은 글자라는 걸 나란히 놓고
   봐야 알기 때문이다. 칩에도 위에 대문자, 아래 소문자가 같이 나온다.

   좌표계 1000×700. 글자는 네 줄 공책처럼 가로선 넷을 기준으로 그린다.

     TOP  145  ─── 대문자 위 = 소문자 윗기둥(b·d·f·h·k·l·t)
     XT   347  ─── 소문자 몸통 위
     BASE 565  ─── 밑줄
     DESC 695  ─── 꼬리(g·j·p·q·y)

   strokes 의 순서가 곧 획순 — 초등 영어 학습지의 통용 필순
   (Zaner-Bloser 계열: 세로 먼저, 왼쪽 먼저, 위에서 아래로)을 따랐다.

   곡선은 arc() 를 poly() 에 펼쳐 만든다. **각이 커지는 쪽이 화면상
   시계 방향**이다 — c·o·s 처럼 반시계로 쓰는 글자는 각을 줄여 간다.
   ============================================================ */

